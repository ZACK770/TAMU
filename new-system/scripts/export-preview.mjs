let html=readFileSync(resolve(root,'public/bifnim/index.html'),'utf8').replace('<link rel="stylesheet" href="/bifnim/style.css">','<style>'+css+'</style>').replace('<script type="module" src="/bifnim/app.mjs"></script>','');
html=html.replace('<body>','<body><div class="preview-ribbon">תצוגת עיצוב בלבד · התכנים לדוגמה · הרשמה, ניקוד והזמנות דורשים את הפעלת השרת המצורף</div>');
