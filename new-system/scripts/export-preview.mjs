const catalog=await youthCatalog(db);
const css=readFileSync(resolve(root,'public/bifnim/style.css'),'utf8');
let js=readFileSync(resolve(root,'public/bifnim/app.mjs'),'utf8').replace("import {BRAND as copy} from './copy.mjs';",'const copy='+JSON.stringify(catalog.brand)+';');
