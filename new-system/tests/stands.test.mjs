import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {sqliteAdapter} from '../scripts/sqlite-adapter.mjs';
import * as Y from '../lib/youth.mjs';
import * as B from '../lib/booklets.mjs';
import * as S from '../lib/staff.mjs';
import * as St from '../lib/stands.mjs';
import {handleAdmin} from '../lib/admin-http.mjs';
function fixture(){const {db,sql}=sqliteAdapter();sql.exec(readFileSync(new URL('../db/portable-schema.sql',import.meta.url),'utf8'));return {db,sql}}
test('stands: assign codes, operator report, tefillin marks, funnel and goals',async()=>{
 const {db}=fixture(),admin={id:'admin',role:'admin'};
 await Y.registerYouth(db,{name:'נער בדיקה',username:'standa',password:'password123'});const pid=(await Y.loginYouth(db,'standa','password123')).participant.id;
 await Y.saveYouthExam(db,{title:'Stand exam',materialKey:'st-m1',week:'st-w1',track:'easy',kind:'sicha',opensAt:new Date(Date.now()-10000).toISOString(),closesAt:new Date(Date.now()+86400000).toISOString(),questionCount:1,questions:[{id:'q1',text:'Q1',options:['A','B'],correct:0,points:10}],published:true});
 const exam=(await B.listBooklets(db)).exams[0];
 await assert.rejects(B.saveBooklet(db,{title:'x',nextUrl:'javascript:alert(1)'}),/https/);
 const {id:bid}=await B.saveBooklet(db,{title:'חוברת דוכן',examId:exam.id,nextText:'בוא לשיעור',nextUrl:'https://x.test/class'});
 await B.generateCodes(db,bid,5);const codes=(await B.bookletCodes(db,bid)).codes;
 const {id:sid}=await handleAdmin(db,admin,'saveStand',{name:'דוכן כיכר',city:'ירושלים'});
 const {id:sid2}=await St.saveStand(db,{name:'דוכן 2'},'admin');
 await assert.rejects(S.createStaff(db,{username:'op0',name:'x',password:'longpassword1',role:'operator'},'admin'),/דוכן/);
 const op=await S.createStaff(db,{username:'op1',name:'מפעיל',password:'longpassword1',role:'operator',scope:{stand:sid}},'admin');
 const opStaff={id:op.id,role:'operator',scope:{stand:sid}};
 assert.equal((await handleAdmin(db,admin,'assignCodes',{bookletId:bid,standId:sid,from:1,to:3,operatorId:op.id})).count,3);
 await assert.rejects(handleAdmin(db,opStaff,'stands'),/הרשאה/);
 let h=await handleAdmin(db,opStaff,'operatorHome');assert.equal(h.booklets[0].assigned,3);
 await handleAdmin(db,opStaff,'standReport',{handed:{[bid]:'3'},tefillin:'4',notes:'יום טוב'});
 await handleAdmin(db,opStaff,'standReport',{handed:{[bid]:3},tefillin:5});
 await assert.rejects(handleAdmin(db,opStaff,'standReport',{handed:{nope:1}}),/שויכה/);
 assert.equal((await handleAdmin(db,opStaff,'markTefillin',{code:B.fmtCode(codes[0].code)})).booklet,'חוברת דוכן');
 await assert.rejects(handleAdmin(db,opStaff,'markTefillin',{code:codes[0].code}),/כבר סומן/);
 const r=await Y.redeemBookletCode(db,pid,codes[0].code);
 let v=await Y.saveYouthChoice(db,pid,r.attempt.id,'q1',0,r.attempt.revision);
 if(!v.completed)v=await Y.submitYouthAttempt(db,pid,r.attempt.id,v.revision);
 assert.ok(v.completed);assert.equal(v.next.text,'בוא לשיעור');
 await St.nextClick(db,pid,bid);await St.nextClick(db,pid,bid);
 await assert.rejects(St.assignCodes(db,{bookletId:bid,standId:sid2,from:1,to:3},'admin'),/דוכן אחר/);
 const f=await handleAdmin(db,admin,'funnel',{});const row=f.rows.find(x=>x.standId===sid);
 assert.deepEqual([row.assigned,row.handed,row.entered,row.completed,row.deepened],[3,3,1,1,1]);
 assert.deepEqual(f.stands.find(s=>s.standId===sid),{standId:sid,stand:'דוכן כיכר',tefillin:5,marked:1});
 const g=await handleAdmin(db,admin,'goals',{});assert.deepEqual([g.actual.learners,g.actual.tefillin,g.actual.handed,g.actual.marked,g.actual.entered],[1,5,3,1,1]);
 assert.equal((await handleAdmin(db,admin,'saveGoals',{targets:{learners:50}})).targets.learners,50);
});
